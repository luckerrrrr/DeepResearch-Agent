"""全部提示词集中管理。模板里含 JSON 示例的花括号，因此用 render() 做占位符替换而不是 str.format。"""


def render(template: str, **values: object) -> str:
    for key, value in values.items():
        template = template.replace("{" + key + "}", str(value))
    return template


